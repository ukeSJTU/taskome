import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const docsRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (relativePath) => readFile(path.join(docsRoot, relativePath), "utf8");
const publicContract = await read("openapi.public.json");
const publishedContract = await read("public/openapi.json");

assert.equal(publishedContract, publicContract);

const schema = JSON.parse(publicContract);

assert.equal(schema.servers.length, 1);
assert.match(schema.servers[0].url, /^https?:\/\/[^/]+(?:\/v1)$/);
assert.deepEqual(schema.components.securitySchemes, {
  APIKeyHeader: { in: "header", name: "X-API-Key", type: "apiKey" },
});
assert.deepEqual(schema.components.schemas.CredentialKind.enum, ["personal_api_key"]);
for (const page of ["auth", "input-files", "jobs"]) {
  const content = await read(`generated/api/${page}.mdx`);
  assert.match(content, /This file was generated by Fumadocs/);
}

const apiIndex = await read("content/docs/api/index.mdx");
assert.match(apiIndex, /does not execute requests from this site/);
