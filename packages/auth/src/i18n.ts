function requestLocale(ctx: { request?: Request }) {
  const locale = ctx.request?.headers.get("x-taskome-locale");
  if (locale === "zh" || locale === "zh-CN" || locale === "en") return locale;
  return null;
}

export function authI18nPlugin() {
  return i18n({
    translations: {
      zh: simplifiedChineseAuthErrors,
      "zh-CN": simplifiedChineseAuthErrors,
    },
    defaultLocale: "en",
    detection: ["callback", "cookie", "header"],
    getLocale: requestLocale,
    localeCookie: "NEXT_LOCALE",
  });
}
